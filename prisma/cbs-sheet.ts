/**
 * Opening a CBS workbook — the one way everything reads one.
 *
 * Two workbooks live in `prisma/data`: the condensed master people edit
 * (`CBS.master.xlsx`) and the expanded sheet `cbs:expand` generates from it
 * (`CBS.xlsx`), which the loader, CBS Health and `cbs:import` read. Both have
 * the same shape — a header row somewhere in the first ten rows, columns found
 * by header rather than by letter — and the loader, the expand script and the
 * rename script each used to find the sheet and its headers their own way.
 * They go through `openCbsSheet` now, so the rules (which sheet, which row is
 * the header, how a column is matched) exist once.
 *
 * Read side only. Writing cells back is `cbs-workbook-cells.ts`.
 */
import ExcelJS from "exceljs";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { unzipSync, zipSync, strToU8, strFromU8 } from "fflate";

const DATA_DIR = join(dirname(fileURLToPath(import.meta.url)), "data");

/** The expanded workbook the loader reads — generated by `cbs:expand`. */
export const CBS_WORKBOOK_PATH = join(DATA_DIR, "CBS.xlsx");
/** The condensed master people edit — the input to `cbs:expand`. */
export const CBS_MASTER_PATH = join(DATA_DIR, "CBS.master.xlsx");

/** Sheet names to look for, in order, before falling back to the first. */
export const SHEET_NAMES = ["CBS", "CBS Expanded", "Master CBS"] as const;

/**
 * ExcelJS throws on the `colorFilter` autofilter nodes inside Excel Tables.
 * Strip the table parts in memory — only cell values are needed. A no-op for
 * workbooks without tables.
 */
export function stripTables(bytes: Uint8Array): Uint8Array {
  const files = unzipSync(bytes);
  const out: Record<string, Uint8Array> = {};
  for (const [path, data] of Object.entries(files)) {
    if (path.startsWith("xl/tables/")) continue;
    if (path.startsWith("xl/worksheets/") && path.endsWith(".xml")) {
      out[path] = strToU8(
        strFromU8(data).replace(/<tableParts[^>]*>[\s\S]*?<\/tableParts>/g, ""),
      );
    } else if (path.includes("/worksheets/_rels/") && path.endsWith(".rels")) {
      out[path] = strToU8(
        strFromU8(data).replace(
          /<Relationship[^>]*relationships\/table[^>]*\/>/g,
          "",
        ),
      );
    } else if (path === "[Content_Types].xml") {
      out[path] = strToU8(
        strFromU8(data).replace(
          /<Override[^>]*spreadsheetml\.table\+xml[^>]*\/>/g,
          "",
        ),
      );
    } else {
      out[path] = data;
    }
  }
  return zipSync(out);
}

export type CbsSheet = {
  path: string;
  ws: ExcelJS.Worksheet;
  /** The 1-based row holding the headers; data starts on the next one. */
  headerRow: number;
  /** 1-based column index by exact header text. */
  column: Record<string, number>;
  /**
   * A column by header: the exact header, else the first one starting with
   * `label` ("P6 Cost Account" finds "P6 Cost Account (L1-4)"). 0 when there
   * is none, so `if (!col(label))` reads as "missing".
   */
  col: (label: string) => number;
};

/**
 * Opens the CBS sheet of a workbook: the first sheet named in `SHEET_NAMES`,
 * else the first sheet (a renamed tab must not break the import — the header
 * row is what says we are reading the right thing), with its header row found
 * wherever "Display Code" appears in the first ten rows (row 1 in the CBS
 * sheets, lower in a dictionary-style sheet with a title block).
 */
export async function openCbsSheet(
  path: string = CBS_WORKBOOK_PATH,
): Promise<CbsSheet> {
  const wb = new ExcelJS.Workbook();
  await wb.xlsx.load(Buffer.from(stripTables(readFileSync(path))) as never);
  const ws =
    SHEET_NAMES.map((n) => wb.getWorksheet(n)).find(Boolean) ??
    wb.worksheets[0];
  if (!ws) throw new Error(`${path}: workbook has no sheets`);

  let headerRow = 0;
  /** Header text by 1-based column; index 0 is unused. */
  let headers: string[] = [];
  for (let r = 1; r <= Math.min(ws.rowCount, 10) && !headerRow; r++) {
    const found: string[] = [];
    ws.getRow(r).eachCell({ includeEmpty: true }, (cell, c) => {
      found[c] = (cell.text ?? "").trim();
    });
    if (found.includes("Display Code")) {
      headerRow = r;
      headers = found;
    }
  }
  if (!headerRow) {
    throw new Error(`${path} [${ws.name}]: no header row with "Display Code"`);
  }

  const column: Record<string, number> = {};
  headers.forEach((h, c) => {
    if (h && !(h in column)) column[h] = c;
  });
  const col = (label: string): number => {
    if (label in column) return column[label];
    const i = headers.findIndex((h) => h && h.startsWith(label));
    return i > 0 ? i : 0;
  };
  return { path, ws, headerRow, column, col };
}

/** A cell's text, trimmed, by header label; "" when the column is absent. */
export function cellText(
  sheet: CbsSheet,
  row: ExcelJS.Row,
  label: string,
): string {
  const n = sheet.col(label);
  return n > 0 ? `${row.getCell(n).text ?? ""}`.trim() : "";
}

/** The A1 address of `label`'s cell on sheet row `row`. */
export function cellAddress(
  sheet: CbsSheet,
  label: string,
  row: number,
): string {
  return `${sheet.ws.getColumn(sheet.col(label)).letter}${row}`;
}

/** What a cell holds once ExcelJS's wrappers are peeled off. */
export type CbsCellValue = string | number | boolean | null;

/**
 * A cell's value as a plain string, number, boolean or null: rich text joined,
 * a formula read as its result, a hyperlink as its text, an error as null.
 * For callers that need the typed value rather than `cellText`'s string —
 * the expand script, which carries numbers and booleans through to the sheet
 * it writes.
 */
export function plainCellValue(v: ExcelJS.CellValue): CbsCellValue {
  if (v === null || v === undefined) return null;
  if (
    typeof v === "string" ||
    typeof v === "number" ||
    typeof v === "boolean"
  ) {
    return v;
  }
  if (v instanceof Date) return v.toISOString();
  if (typeof v === "object") {
    if ("richText" in v) return v.richText.map((t) => t.text).join("");
    if ("result" in v) return plainCellValue(v.result as ExcelJS.CellValue);
    if ("text" in v) return plainCellValue(v.text as ExcelJS.CellValue);
    if ("error" in v) return null;
  }
  return `${v}`;
}
