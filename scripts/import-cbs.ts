// Re-imports the CBS Dictionary from `prisma/data/CBS.xlsx` into the
// `CbsItem` table WITHOUT touching anything else (projects, FEF rows, change
// logs, etc.). This is the regular "the CBS changed" process:
//
//   1. Drop the new workbook in at prisma/data/CBS.xlsx
//   2. npm run cbs:import -- --dry-run     (review the plan + workbook report)
//   3. npm run cbs:import
//
// Unlike the full `seedBaseData()`, this preserves each project's CBS allow-list:
// it upserts by the unique `costCode`, so existing items keep their row id (and
// therefore their `ProjectAllowedFefCbsItems` join rows). Items whose costCode no
// longer appears in the dictionary are deleted (their allow-list entries cascade
// away — the code is gone). Brand-new items are created but NOT auto-added to
// any allow-list; the run reports how many, so you can grant them in Setup.
//
// CBS.xlsx is generated by `cbs:expand` from the condensed master
// (CBS.master.xlsx): every row flagged Labor / Sub / Material / Equipment /
// Other / Rental Code already has its typed companion in the sheet, so the
// loader generates nothing and stores one item per sheet row. What it does to
// every row is normalize a four-segment summary code to the "-0" backbone;
// names keep the roll-up's trailing "*". See `prisma/cbs-workbook.ts`.
//
// Existing rows are compared column-by-column against the workbook and only
// the ones that actually differ are written, a whole batch per statement
// (`cbsBulkUpdateSql`), so even a renumber that touches most of the catalog is
// a handful of round trips rather than one per row.
//
// Run:  npx tsx scripts/import-cbs.ts [--dry-run] [--workbook <path>]
// With --dry-run, --expect-current fails unless there is nothing to do.
//
// --workbook reads a different expanded workbook than prisma/data/CBS.xlsx,
// for when that file is locked (open in Excel) and `cbs:expand -- --out` had
// to write elsewhere. The database ends up the same; the canonical file still
// needs regenerating afterwards, because CBS Health reads it.
import "dotenv/config";
import { statSync } from "node:fs";
import { prisma } from "../src/server/db";
import { CBS_WORKBOOK_PATH } from "../prisma/cbs-sheet";
import {
  formatCbsWorkbookReport,
  loadCbsWorkbook,
  type CbsDictionaryRow,
} from "../prisma/cbs-workbook";
import {
  CBS_IMPORT_FIELDS,
  cbsBulkUpdateSql,
  changedCbsFields,
  type CbsImportField,
} from "../src/lib/cbs-import-diff";

const dryRun = process.argv.includes("--dry-run");
const workbookArg = process.argv.indexOf("--workbook");
const workbookPath =
  workbookArg >= 0 ? process.argv[workbookArg + 1] : undefined;
// Rows per bulk UPDATE. Each row is ~1 KB of JSON, so a batch stays well
// inside a single statement's comfortable size.
const CHUNK = 1000;

async function main() {
  const { items, report } = await loadCbsWorkbook(workbookPath);
  console.log(formatCbsWorkbookReport(report));

  // Guard: costCode is the upsert key and is @unique — refuse to run on data
  // that would violate it rather than fail halfway through.
  const byCost = new Map(items.map((i) => [i.costCode, i]));
  if (byCost.size !== items.length) {
    throw new Error(
      `Dictionary not loadable: ${items.length - byCost.size} duplicate costCode(s) after expansion.`,
    );
  }

  const existing = await prisma.cbsItem.findMany({
    select: Object.fromEntries(
      [...CBS_IMPORT_FIELDS, "costCode"].map((f) => [f, true]),
    ) as { [K in CbsImportField | "costCode"]: true },
  });
  const existingByCost = new Map(existing.map((e) => [e.costCode, e]));

  const toDelete = existing
    .filter((e) => !byCost.has(e.costCode))
    .map((e) => e.costCode);
  const toCreate = items.filter((i) => !existingByCost.has(i.costCode));
  const toUpdate: { row: CbsDictionaryRow; changed: string[] }[] = [];
  let unchanged = 0;
  for (const it of items) {
    const prior = existingByCost.get(it.costCode);
    if (!prior) continue;
    const diff = changedCbsFields(prior, it);
    if (diff) toUpdate.push({ row: it, changed: Object.keys(diff) });
    else unchanged++;
  }

  console.log(
    `\nDictionary rows: ${items.length} | DB existing: ${existing.length}`,
  );
  console.log(
    `Plan → create ${toCreate.length}, update ${toUpdate.length}, unchanged ${unchanged}, delete (stale) ${toDelete.length}`,
  );
  if (dryRun) {
    if (toCreate.length) {
      console.log(
        `New codes (first 20): ${toCreate
          .slice(0, 20)
          .map((c) => c.costCode)
          .join(", ")}`,
      );
    }
    if (toDelete.length) {
      console.log(
        `Stale codes (first 20): ${toDelete.slice(0, 20).join(", ")}`,
      );
    }
    if (toUpdate.length) {
      const sample = toUpdate
        .slice(0, 10)
        .map((u) => `${u.row.costCode} [${u.changed.join(", ")}]`)
        .join("; ");
      console.log(`Changed rows (first 10): ${sample}`);
    }
    // What deleting the stale codes takes off each project's allow-list.
    const losing = toDelete.length
      ? await prisma.project.findMany({
          where: {
            allowedFefCbsItems: { some: { costCode: { in: toDelete } } },
          },
          orderBy: { id: "asc" },
          select: {
            name: true,
            allowedFefCbsItems: {
              where: { costCode: { in: toDelete } },
              orderBy: { displayCode: "asc" },
              select: { displayCode: true },
            },
          },
        })
      : [];
    for (const p of losing) {
      const codes = p.allowedFefCbsItems.map((c) => c.displayCode);
      console.log(
        `Grants removed from ${p.name}: ${codes.length} (${codes.slice(0, 20).join(", ")})`,
      );
    }
    console.log("\n--dry-run: no changes written.");
    if (
      process.argv.includes("--expect-current") &&
      toCreate.length + toUpdate.length + toDelete.length > 0
    ) {
      throw new Error("The database does not match the workbook.");
    }
    return;
  }

  // All or nothing: a failure partway — including writing the record at the
  // end — leaves the catalog and every allow-list as they were. The timeout is
  // explicit because Prisma's 5 s default is easy to pass on a remote pooler.
  const finalCount = await prisma.$transaction(
    async (tx) => {
      if (toDelete.length) {
        const del = await tx.cbsItem.deleteMany({
          where: { costCode: { in: toDelete } },
        });
        console.log(`Deleted ${del.count} stale CbsItems.`);
      }

      for (let i = 0; i < toCreate.length; i += 500) {
        await tx.cbsItem.createMany({ data: toCreate.slice(i, i + 500) });
      }
      if (toCreate.length)
        console.log(`Created ${toCreate.length} new CbsItems.`);

      // Update in place — keeps the row id, so allow-list join rows survive.
      // One statement per batch.
      const sql = cbsBulkUpdateSql();
      for (let i = 0; i < toUpdate.length; i += CHUNK) {
        const chunk = toUpdate
          .slice(i, i + CHUNK)
          .map(({ row }) =>
            Object.fromEntries(
              ["costCode", ...CBS_IMPORT_FIELDS].map((f) => [
                f,
                row[f as keyof CbsDictionaryRow],
              ]),
            ),
          );
        const n = await tx.$executeRawUnsafe(sql, JSON.stringify(chunk));
        if (n !== chunk.length) {
          throw new Error(
            `Bulk update wrote ${n} of ${chunk.length} rows — a costCode went missing mid-import.`,
          );
        }
        console.log(
          `  updated ${Math.min(i + CHUNK, toUpdate.length)}/${toUpdate.length}…`,
        );
      }
      console.log(
        `Updated ${toUpdate.length} changed CbsItems (${unchanged} unchanged).`,
      );

      const finalCount = await tx.cbsItem.count();
      console.log(`\nFinal CbsItem count: ${finalCount}`);

      // Leave a record: the Code Book reads the latest to say when the CBS last
      // changed. In the same transaction as the rows, so the two cannot disagree.
      const record = await tx.cbsImport.create({
        data: {
          workbookModified: statSync(workbookPath ?? CBS_WORKBOOK_PATH).mtime,
          workbookRows: items.length,
          created: toCreate.length,
          updated: toUpdate.length,
          unchanged,
          deleted: toDelete.length,
          finalCount,
        },
      });
      console.log(
        `Recorded as CBS import #${record.id} at ${record.importedAt.toISOString()}.`,
      );
      return finalCount;
    },
    { maxWait: 20_000, timeout: 300_000 },
  );

  const projs = await prisma.project.findMany({
    select: {
      id: true,
      name: true,
      _count: { select: { allowedFefCbsItems: true } },
    },
    orderBy: { id: "asc" },
  });
  console.log("Project CBS allow-lists after import:");
  for (const p of projs) {
    const gap = finalCount - p._count.allowedFefCbsItems;
    const note =
      p._count.allowedFefCbsItems > 0 && gap > 0
        ? `  (← ${gap} CBS items NOT in this allow-list)`
        : "";
    console.log(
      `  project ${p.id} ${p.name}: ${p._count.allowedFefCbsItems} allowed${note}`,
    );
  }
}

main()
  .then(() => prisma.$disconnect())
  .then(() => process.exit(0))
  .catch((e) => {
    console.error(e);
    process.exit(1);
  });
